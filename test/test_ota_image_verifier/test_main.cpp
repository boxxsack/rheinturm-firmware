void test_valid_signature_is_accepted(void) {
    bool ok = OtaImageVerifier::verify(kTestDigest, kValidSignature, sizeof(kValidSignature), kTestPublicKeyPem);
    TEST_ASSERT_TRUE_MESSAGE(ok, "a correctly signed image must verify");
}

void test_tampered_digest_is_rejected(void) {
    uint8_t tamperedDigest[32];
    memcpy(tamperedDigest, kTestDigest, sizeof(tamperedDigest));
    tamperedDigest[0] ^= 0xFF;  // simulates a modified/corrupted firmware image
    bool ok = OtaImageVerifier::verify(tamperedDigest, kValidSignature, sizeof(kValidSignature), kTestPublicKeyPem);
    TEST_ASSERT_FALSE_MESSAGE(ok, "a signature over a different image must be rejected");
}

void test_wrong_signer_key_is_rejected(void) {
    // Signed by an attacker's private key, not the one matching kTestPublicKeyPem.
    bool ok = OtaImageVerifier::verify(kTestDigest, kAttackerSignature, sizeof(kAttackerSignature), kTestPublicKeyPem);
    TEST_ASSERT_FALSE_MESSAGE(ok, "an image signed by a different keypair must be rejected");
}

void test_unsigned_garbage_signature_is_rejected(void) {
    uint8_t garbage[256];
    memset(garbage, 0x42, sizeof(garbage));
    bool ok = OtaImageVerifier::verify(kTestDigest, garbage, sizeof(garbage), kTestPublicKeyPem);
    TEST_ASSERT_FALSE_MESSAGE(ok, "an unsigned (garbage-signature) image must be rejected");
}

void test_wrong_length_signature_is_rejected(void) {
    // Not the fixed 256-byte RSA-2048 signature size - must be rejected outright,
    // not truncated/padded and checked anyway.
    bool ok = OtaImageVerifier::verify(kTestDigest, kValidSignature, 128, kTestPublicKeyPem);
    TEST_ASSERT_FALSE_MESSAGE(ok, "a wrong-length signature must be rejected outright");
}

void test_malformed_public_key_is_rejected(void) {
    bool ok = OtaImageVerifier::verify(kTestDigest, kValidSignature, sizeof(kValidSignature), "not a pem key");
    TEST_ASSERT_FALSE_MESSAGE(ok, "a malformed embedded public key must fail closed, not crash");
}

void test_embedded_public_key_is_rsa_2048(void) {
#if MBEDTLS_VERSION_MAJOR >= 4
    TEST_ASSERT_EQUAL_INT(PSA_SUCCESS, psa_crypto_init());
#endif

    mbedtls_pk_context pk;
    mbedtls_pk_init(&pk);
    int result = mbedtls_pk_parse_public_key(
        &pk,
        reinterpret_cast<const unsigned char*>(OTA_SIGNING_PUBLIC_KEY),
        std::strlen(OTA_SIGNING_PUBLIC_KEY) + 1);
    if (result != 0) {
        mbedtls_pk_free(&pk);
        TEST_FAIL_MESSAGE("the embedded OTA public key must parse");
        return;
    }

    TEST_ASSERT_TRUE(mbedtls_pk_can_do(&pk, MBEDTLS_PK_RSA));
    TEST_ASSERT_EQUAL_UINT(2048, mbedtls_pk_get_bitlen(&pk));
    mbedtls_pk_free(&pk);
}

int main(int argc, char **argv) {
    UNITY_BEGIN();
    RUN_TEST(test_valid_signature_is_accepted);
    RUN_TEST(test_tampered_digest_is_rejected);
    RUN_TEST(test_wrong_signer_key_is_rejected);
    RUN_TEST(test_unsigned_garbage_signature_is_rejected);
    RUN_TEST(test_wrong_length_signature_is_rejected);
    RUN_TEST(test_malformed_public_key_is_rejected);
    RUN_TEST(test_embedded_public_key_is_rsa_2048);
    return UNITY_END();
}
